-- DECISION: Enable UUID generation extension in PostgreSQL for non-sequential IDs.
-- ALTERNATIVES: BIGSERIAL (rejected: exposes user registration velocity to attackers).
-- SEE: ADR-001
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- DECISION: Dedicated users table owned exclusively by user-service.
-- INVARIANT: Passwords must always be stored as salted BCrypt/Argon2 hashes, never plaintext.
CREATE TABLE IF NOT EXISTS users (
    -- DECISION: UUID primary key generated by database if not supplied by client.
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),

    -- DECISION: Email as natural unique identifier for authentication. Length 255 satisfies RFC 5321.
    email VARCHAR(255) NOT NULL,

    -- DECISION: Store bcrypt hash with standard 60-character output size; VARCHAR(255) allows future algorithm upgrades.
    password_hash VARCHAR(255) NOT NULL,

    -- DECISION: Role enum stored as VARCHAR for readability and easy migration.
    -- Allowed values: 'CUSTOMER', 'RESTAURANT_OWNER', 'RIDER', 'ADMIN'
    role VARCHAR(50) NOT NULL,

    -- DECISION: Separate display name and contact phone for delivery verification.
    name VARCHAR(100) NOT NULL,
    phone VARCHAR(20) NOT NULL,

    -- DECISION: Audit timestamps with timezone to track registration and updates accurately.
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- INVARIANT: No two users can register with the same email.
    CONSTRAINT uk_users_email UNIQUE (email)
);

-- DECISION: B-tree index on email accelerates login lookups (WHERE email = ?).
CREATE INDEX IF NOT EXISTS idx_users_email ON users(email);

-- DECISION: B-tree index on role allows fast filtering by actor type (e.g. finding all active riders).
CREATE INDEX IF NOT EXISTS idx_users_role ON users(role);
